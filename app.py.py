def actualizar(deptos, ind, amin_ui, amax_ui, anio_mapa):
    st = stats(DF, deptos, ind, amin_ui, amax_ui)
    fig_t = tendencia(DF, deptos, ind, amin_ui, amax_ui)
    ind_b = ind if ind != "Todos" else (lista_inds[1] if len(lista_inds) > 1 else ind)
    fig_b = barras(DF, ind_b, anio_mapa)
    tabla = filtrar(DF, deptos, ind, amin_ui, amax_ui).head(400)
    return st, fig_t, fig_b, tabla

